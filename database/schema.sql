CREATE TABLE IF NOT EXISTS jobs (
    job_id TEXT PRIMARY KEY,
    dedupe_key TEXT,
    title TEXT NOT NULL,
    company TEXT NOT NULL,
    location TEXT,
    country TEXT,
    remote_status TEXT,
    employment_type TEXT,
    salary TEXT,
    salary_currency TEXT,
    experience_required TEXT,
    education_required TEXT,
    technologies TEXT,
    responsibilities TEXT,
    mandatory_requirements TEXT,
    preferred_requirements TEXT,
    language_requirements TEXT,
    visa_work_authorization_requirements TEXT,
    application_url TEXT,
    source TEXT,
    original_posting_date TEXT,
    discovered_date TEXT,
    closing_date TEXT,
    company_career_url TEXT,
    full_job_description TEXT,
    application_platform TEXT,
    score REAL,
    status TEXT NOT NULL DEFAULT 'NEW',
    availability_status TEXT NOT NULL DEFAULT 'UNKNOWN',
    last_checked_at TEXT,
    status_reason TEXT,
    status_updated_at TEXT,
    notes TEXT,
    created_at TEXT DEFAULT CURRENT_TIMESTAMP,
    updated_at TEXT DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS applications (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    job_id TEXT NOT NULL,
    cv_version TEXT,
    cover_letter TEXT,
    answers TEXT,
    date_prepared TEXT,
    date_submitted TEXT,
    submitted_date_precision TEXT NOT NULL DEFAULT 'UNKNOWN',
    status TEXT,
    status_reason TEXT,
    response TEXT,
    interview TEXT,
    rejection TEXT,
    notes TEXT,
    FOREIGN KEY(job_id) REFERENCES jobs(job_id)
);
